#!/usr/bin/env python3
"""Cut the "2D HD Character Knight" sheets (15 columns x 8 facings of 128px cells) down to the animations the village hero uses.

  python3 -I tools/extract_knight.py "<.../Spritesheets/With shadows>" assets/sprites/knight

Per sheet: the baked-in ground shadow is removed (the village draws its own), every frame is trimmed to one shared box per sheet,
and the result is written as assets/sprites/knight/<Name>.png plus assets/sprites/knight/atlas.js (window.KNIGHT_ATLAS), a plain script
so the village still opens straight from file://. Row order in the sheets is SE, S, SW, W, NW, N, NE, E.
"""
import json, os, sys
import numpy as np
from PIL import Image

SRC, DST = sys.argv[1], sys.argv[2]
SHEETS = ['Idle', 'Run', 'Melee', 'Pummel', 'Special1', 'TakeDamage', 'Die', 'CastSpell']
COLS, ROWS, CELL = 15, 8, 128
ROW_DIRS = ['SE', 'S', 'SW', 'W', 'NW', 'N', 'NE', 'E']

def strip_shadow(a):
    """Shadow = near-black, partly transparent pixels. Character outlines are opaque, so they survive."""
    m = (a[..., 3] > 0) & (a[..., 3] < 250) & (a[..., :3].max(axis=2) < 40)
    a = a.copy(); a[m] = 0
    return a

os.makedirs(DST, exist_ok=True)
atlas = {'cols': COLS, 'rows': ROWS, 'dirs': ROW_DIRS, 'cell': CELL, 'sheets': {}}
feet = []
for name in SHEETS:
    arr = strip_shadow(np.array(Image.open(os.path.join(SRC, name + '.png')).convert('RGBA')))
    x0, y0, x1, y1 = CELL, CELL, 0, 0
    for r in range(ROWS):
        for c in range(COLS):
            cl = arr[r * CELL:(r + 1) * CELL, c * CELL:(c + 1) * CELL, 3]
            ys, xs = np.nonzero(cl > 8)
            if len(xs):
                x0, x1, y0, y1 = min(x0, xs.min()), max(x1, xs.max()), min(y0, ys.min()), max(y1, ys.max())
                if name == 'Idle': feet.append((ys.max(), (xs.min() + xs.max()) / 2))
    x0, y0, x1, y1 = max(0, x0 - 1), max(0, y0 - 1), min(CELL - 1, x1 + 1), min(CELL - 1, y1 + 1)
    w, h = x1 - x0 + 1, y1 - y0 + 1
    out = Image.new('RGBA', (w * COLS, h * ROWS))
    for r in range(ROWS):
        for c in range(COLS):
            cell = arr[r * CELL + y0:r * CELL + y0 + h, c * CELL + x0:c * CELL + x0 + w]
            out.paste(Image.fromarray(cell, 'RGBA'), (c * w, r * h))
    path = os.path.join(DST, name + '.png')
    out.save(path, optimize=True)
    atlas['sheets'][name] = {'file': 'assets/sprites/knight/' + name + '.png', 'ox': int(x0), 'oy': int(y0), 'w': int(w), 'h': int(h)}
    print(name, (w, h), os.path.getsize(path) // 1024, 'KB')
# the feet: where the standing figure touches the ground, in cell coordinates (median over every idle frame)
fy = int(np.median([f[0] for f in feet])); fx = int(np.median([f[1] for f in feet]))
atlas['anchor'] = [fx, fy]
print('anchor', fx, fy)
with open(os.path.join(DST, 'atlas.js'), 'w') as f:
    f.write('// generated by tools/extract_knight.py\nwindow.KNIGHT_ATLAS = ' + json.dumps(atlas) + ';\n')
